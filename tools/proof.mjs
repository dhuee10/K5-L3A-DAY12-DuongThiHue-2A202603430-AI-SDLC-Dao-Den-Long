// Regenerates Phase 1 evidence from the REAL headless CLI. Never edit the outputs by hand.
//   npm run proof   ->  docs/proof/phase-3/scenarios/<id>/{scenario,inputs}.json + output.jsonl, docs/proof/phase-3/RESULTS.md
import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import os from 'node:os';
import { SCENARIOS } from '../tests/scenarios.mjs';

const OUT = 'docs/proof/phase-3';
const cli = (args) => spawnSync(process.execPath, ['src/headless.mjs', ...args], { encoding: 'utf8' });
rmSync(join(OUT, 'scenarios'), { recursive: true, force: true });

const rows = [];
let allOk = true;
for (const sc of SCENARIOS) {
  const dir = join(OUT, 'scenarios', sc.id);
  mkdirSync(dir, { recursive: true });
  const args = ['--seed', '1', '--night', String(sc.night ?? 1), '--ticks', String(sc.ticks), '--out', join(dir, 'output.jsonl'), '--snapshot-every', String(sc.every ?? 10)];
  if (sc.scenario) { writeFileSync(join(dir, 'scenario.json'), JSON.stringify(sc.scenario, null, 2)); args.push('--scenario', join(dir, 'scenario.json')); }
  if (sc.inputs) { writeFileSync(join(dir, 'inputs.json'), JSON.stringify(sc.inputs, null, 2)); args.push('--inputs', join(dir, 'inputs.json')); }
  const r = cli(args);
  let checks;
  if (r.status !== 0) checks = [[false, `exit ${r.status}: ${r.stderr.trim()}`]];
  else {
    const lines = readFileSync(join(dir, 'output.jsonl'), 'utf8').trim().split('\n').map((l) => JSON.parse(l));
    try { checks = sc.check(lines); } catch (e) { checks = [[false, `check threw: ${e.message}`]]; }
  }
  const ok = checks.every(([c]) => c);
  allOk &&= ok;
  writeFileSync(join(dir, 'command.txt'), `node src/headless.mjs ${args.join(' ')}\n`);
  rows.push(`| ${sc.id} | ${sc.req} | [output](scenarios/${sc.id}/output.jsonl) | ${ok ? 'PASS' : 'FAIL'} | ${checks.map(([c, m]) => (c ? '' : 'FAILED: ') + m).join('; ').replace(/\|/g, '/')} |`);
}

// determinism: same seed twice through the CLI, full default night
const hash = (f) => createHash('sha256').update(readFileSync(f)).digest('hex').slice(0, 16);
const tmp = os.tmpdir();
// Mây (999 flames, so she survives wind + hits) waits at lit L1 so Night 3 runs the full 18000 ticks (300 s) until dawn with every spawner + wind active.
const fullSc = join(tmp, 'ddl-full.json');
writeFileSync(fullSc, JSON.stringify({ player: { pos: [0, 6, 6], flames: 999 }, lanterns: [{ id: 'L1', lit: true }] }));
const runFull = (seed, name) => { const t = performance.now(); const r = cli(['--seed', String(seed), '--night', '3', '--ticks', '18000', '--scenario', fullSc, '--out', join(tmp, name)]); return { r, ms: performance.now() - t }; };
const a = runFull(7, 'ddl-a.jsonl'), b = runFull(7, 'ddl-b.jsonl'), c = runFull(8, 'ddl-c.jsonl');
const ha = hash(join(tmp, 'ddl-a.jsonl')), hb = hash(join(tmp, 'ddl-b.jsonl')), hc = hash(join(tmp, 'ddl-c.jsonl'));
const detOk = a.r.status === 0 && ha === hb && ha !== hc;
allOk &&= detOk;
const endA = readFileSync(join(tmp, 'ddl-a.jsonl'), 'utf8').trim().split('\n').at(-1);

// malformed input -> exit 2
writeFileSync(join(tmp, 'ddl-bad.json'), '{"frames":[{"tick":3},{"tick":2}]}');
const bad = cli(['--seed', '1', '--night', '1', '--ticks', '5', '--out', join(tmp, 'x.jsonl'), '--inputs', join(tmp, 'ddl-bad.json')]);
const badOk = bad.status === 2;
allOk &&= badOk;

const md = `# Phase 3 headless evidence (generated)

Generated by \`npm run proof\` (tools/proof.mjs) from the real CLI \`node src/headless.mjs\`. Do not edit by hand.
Machine: ${os.cpus()[0]?.model ?? 'unknown'}, ${os.platform()} ${os.release()}, Node ${process.version}.

## Requirement scenarios (seed 1)

| ID | Requirement | Evidence | Result | Checked |
|---|---|---|---|---|
${rows.join('\n')}

## Determinism + performance (full Night 3, 18000 ticks = 300 s, all spawners + wind + fuel; limit 30 s)

| Run | sha256 (16) | Exit | Time |
|---|---|---|---|
| seed 7, run 1 | ${ha} | ${a.r.status} | ${a.ms.toFixed(0)} ms |
| seed 7, run 2 | ${hb} | ${b.r.status} | ${b.ms.toFixed(0)} ms |
| seed 8 | ${hc} | ${c.r.status} | ${c.ms.toFixed(0)} ms |

Result: **${detOk ? 'PASS' : 'FAIL'}** (same seed identical, different seed differs). End line of seed 7 (Mây waits at lit L1, 999 flames): \`${endA}\`

## Malformed inputs

Non-increasing frame ticks -> exit code ${bad.status}, stderr: \`${bad.stderr.trim()}\`. Result: **${badOk ? 'PASS' : 'FAIL'}**

## Overall: ${allOk ? 'ALL PASS' : 'SOME FAILED'}
`;
writeFileSync(join(OUT, 'RESULTS.md'), md);
console.log(md.split('\n').filter((l) => /FAIL|Overall/.test(l)).join('\n'));
process.exit(allOk ? 0 : 1);
